package org.opensearch.serverless.engine;

import org.opensearch.index.engine.DeletionStrategy;
import org.opensearch.index.engine.Engine;
import org.opensearch.index.engine.IndexingStrategy;
import org.opensearch.index.engine.OperationStrategyPlanner;
import org.opensearch.index.engine.PrimaryOperationPolicy;
import org.opensearch.index.seqno.SequenceNumbers;

import java.io.IOException;

/** Applies already resolved upstream identities without repeating primary CAS/version allocation. */
final class CommittedPrimaryOperationPolicy implements PrimaryOperationPolicy {
    static final CommittedPrimaryOperationPolicy INSTANCE = new CommittedPrimaryOperationPolicy();

    private CommittedPrimaryOperationPolicy() {}

    @Override
    public boolean acceptsPreAssignedSeqNos() {
        return true;
    }

    @Override
    public IndexingStrategy planIndex(OperationStrategyPlanner<Engine.Index, IndexingStrategy> planner, Engine.Index index)
        throws IOException {
        return planner.planOperationAsNonPrimary(
            new Engine.Index(
                index.uid(),
                index.parsedDoc(),
                index.seqNo(),
                index.primaryTerm(),
                index.version(),
                null,
                Engine.Operation.Origin.REPLICA,
                index.startTime(),
                index.getAutoGeneratedIdTimestamp(),
                index.isRetry(),
                SequenceNumbers.UNASSIGNED_SEQ_NO,
                SequenceNumbers.UNASSIGNED_PRIMARY_TERM
            )
        );
    }

    @Override
    public DeletionStrategy planDelete(OperationStrategyPlanner<Engine.Delete, DeletionStrategy> planner, Engine.Delete delete)
        throws IOException {
        return planner.planOperationAsNonPrimary(
            new Engine.Delete(
                delete.id(),
                delete.uid(),
                delete.seqNo(),
                delete.primaryTerm(),
                delete.version(),
                null,
                Engine.Operation.Origin.REPLICA,
                delete.startTime(),
                SequenceNumbers.UNASSIGNED_SEQ_NO,
                SequenceNumbers.UNASSIGNED_PRIMARY_TERM,
                delete.routing()
            )
        );
    }
}
